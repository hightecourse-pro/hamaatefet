/**
 * Every text the members see – with its default (the design's wording). The team
 * overrides any of them from /admin/content; a row in site_content wins.
 * kind: text = one line · lines = several lines · rich = sanitized HTML.
 * Placeholders in braces ({שם}, {חודש}…) are filled by the code; the hint says which exist.
 *
 * Pure data – safe to import from client components.
 */
export interface ContentField {
  key: string;
  label: string;
  kind: "text" | "lines" | "rich";
  default: string;
  hint?: string;
}
export interface ContentGroup {
  key: string;
  title: string;
  description?: string;
  fields: ContentField[];
}

const t = (key: string, label: string, def: string, hint?: string): ContentField => ({ key, label, kind: "text", default: def, hint });
const l = (key: string, label: string, def: string, hint?: string): ContentField => ({ key, label, kind: "lines", default: def, hint });
const r = (key: string, label: string, def: string, hint?: string): ContentField => ({ key, label, kind: "rich", default: def, hint });

